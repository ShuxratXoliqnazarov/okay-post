export function FaqPage() {
  const [searchQuery, setSearchQuery] = useState('')
  const [openItems, setOpenItems] = useState({})

  const toggleItem = (key) => {
    setOpenItems((prev) => ({
      ...prev,
      [key]: !prev[key],
    }))
  }

  // Фильтрация вопросов по поисковому запросу
  const filteredSections = useMemo(() => {
    const q = searchQuery.trim().toLowerCase()
    if (!q) return FAQ_SECTIONS

    return FAQ_SECTIONS.map((section) => ({
      ...section,
      items: section.items.filter(
        (item) => item.q.toLowerCase().includes(q) || item.a.toLowerCase().includes(q)
      ),
    })).filter((section) => section.items.length > 0)
  }, [searchQuery])

  return (
    <div className="animate-fade-scale">
      {/* Шапка страницы */}
      <PageHero
        breadcrumbs={[
          { label: 'Главная', to: ROUTES.HOME },
          { label: 'Часто задаваемые вопросы' },
        ]}
        title="Отвечаем на вопросы доставки"
      />

      <Container>
        {/* Поисковая строка */}
        <div className="mx-auto mb-12 max-w-4xl sm:mb-16">
          <div className="relative rounded-[20px] border border-line bg-white p-4 shadow-[0_4px_24px_rgba(31,36,40,0.04)] transition-all duration-300 focus-within:border-primary focus-within:shadow-[0_8px_30px_rgba(0,201,123,0.15)] sm:p-5">
            <label
              htmlFor="faq-search"
              className="block text-xs font-semibold text-muted tracking-wide uppercase"
            >
              Тема или ключевое слово
            </label>
            <div className="mt-1 flex items-center justify-between gap-3">
              <input
                id="faq-search"
                type="text"
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                placeholder="Введите свой вопрос..."
                className="w-full bg-transparent text-base font-medium text-dark placeholder:text-muted/60 focus:outline-none sm:text-lg"
              />
              {searchQuery ? (
                <button
                  type="button"
                  onClick={() => setSearchQuery('')}
                  aria-label="Очистить"
                  className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full text-muted hover:bg-surface hover:text-dark transition-colors"
                >
                  <X size={18} weight="bold" />
                </button>
              ) : (
                <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-primary/10 text-primary">
                  <MagnifyingGlass size={22} weight="bold" />
                </div>
              )}
            </div>
          </div>
        </div>

        {/* Секции с аккордеонами */}
        <div className="mx-auto max-w-4xl space-y-12 sm:space-y-16">
          {filteredSections.length === 0 ? (
            <div className="rounded-2xl border border-line bg-white p-12 text-center text-muted shadow-sm">
              <p className="text-lg font-semibold text-dark">Ничего не найдено</p>
              <p className="mt-2 text-sm">
                По запросу «{searchQuery}» ничего не найдено. Попробуйте изменить формулировку.
              </p>
            </div>
          ) : (
            filteredSections.map((section) => (
              <section key={section.id}>
                <h2 className="mb-6 text-xl font-bold tracking-tight text-dark sm:text-2xl">
                  {section.title}
                </h2>

                <div className="space-y-3">
                  {section.items.map((item, idx) => {
                    const itemKey = `${section.id}-${idx}`
                    const isOpen = Boolean(openItems[itemKey])

                    return (
                      <div
                        key={itemKey}
                        className={cn(
                          'overflow-hidden rounded-2xl border bg-white transition-all duration-300',
                          isOpen
                            ? 'border-primary/60 shadow-[0_4px_20px_rgba(0,201,123,0.08)]'
                            : 'border-line/70 hover:border-line hover:shadow-sm'
                        )}
                      >
                        <button
                          type="button"
                          onClick={() => toggleItem(itemKey)}
                          className="flex w-full items-center justify-between gap-4 p-5 text-left sm:p-6"
                        >
                          <span
                            className={cn(
                              'text-sm font-semibold sm:text-base transition-colors duration-200',
                              isOpen ? 'text-primary' : 'text-dark'
                            )}
                          >
                            {item.q}
                          </span>
                          <span
                            className={cn(
                              'flex h-9 w-9 shrink-0 items-center justify-center rounded-full transition-transform duration-300',
                              isOpen
                                ? 'bg-primary text-white rotate-180 shadow-[0_2px_10px_rgba(0,201,123,0.3)]'
                                : 'bg-surface text-primary hover:bg-primary/10'
                            )}
                          >
                            <CaretDown size={18} weight="bold" />
                          </span>
                        </button>

                        {/* Текст ответа */}
                        {isOpen && (
                          <div className="border-t border-line/40 px-5 pt-4 pb-6 sm:px-6 text-sm sm:text-base leading-relaxed text-muted animate-fade-scale">
                            {item.a}
                          </div>
                        )}
                      </div>
                    )
                  })}
                </div>
              </section>
            ))
          )}
        </div>
      </Container>

      {/* Баннер соцсетей */}
      <SocialBanner />
    </div>
  )
}
